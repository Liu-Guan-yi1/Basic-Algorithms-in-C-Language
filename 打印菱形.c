#include <stdio.h>

int main()
{
    int i, j, k;
    
    // 1. 打印菱形的上半部分（共 4 行，i 从 0 到 3）
    for (i = 0; i <= 3; i++)
    {
        // 打印每行前面的空格：随着行数增加，空格逐渐减少
        for (j = 0; j <= 2 - i; j++)
        {
            printf(" ");
        }
        
        // 打印每行的星号：随着行数增加，星号逐渐增多（奇数个）
        for (k = 0; k <= 2 * i; k++)
        {
            printf("*");
        }
        
        // 一行结束，换行
        printf("\n");
    }
    
    // 2. 打印菱形的下半部分（共 3 行，i 从 0 到 2）
    for (i = 0; i <= 2; i++)
    {
        // 打印每行前面的空格：随着行数增加，空格逐渐增多
        for (j = 0; j <= i; j++)
        {
            printf(" ");
        }
        
        // 打印每行的星号：随着行数增加，星号逐渐减少（奇数个）
        for (k = 0; k <= 4 - 2 * i; k++)
        {
            printf("*");
        }
        
        // 一行结束，换行
        printf("\n");
    }
    
    return 0;
}
